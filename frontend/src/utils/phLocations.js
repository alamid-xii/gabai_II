/**
 * Automatically capitalizes the first letter of the string and the first letter
 * of each word after spaces, hyphens, or periods without eating trailing spaces.
 */
export function autoCapitalizeWords(value) {
  if (typeof value !== "string" || !value) return "";
  return value
    .replace(/(^|[\s\-./])(\p{L})/gu, (match, sep, char) => `${sep}${char.toUpperCase()}`)
    .replace(/\b(Ii|Iii|Iv|Vi|Vii|Viii)\b/g, (roman) => roman.toUpperCase());
}

/**
 * Compute default Grade 6 SY Start & End based on enrollment academicYear (e.g. "2026-2027")
 * and selected gradeLevel (e.g. "Grade 7" -> 2025 to 2026; "Grade 8" -> 2024 to 2025).
 */
export function computeDefaultGrade6SY(academicYear, gradeLevel) {
  const startMatch = String(academicYear || "").match(/^(\d{4})/);
  const baseStartYear = startMatch ? Number(startMatch[1]) : new Date().getFullYear();
  const gradeNum = Number(String(gradeLevel || "").replace(/\D/g, "")) || 7;
  const yearsSinceGrade6 = Math.max(1, gradeNum - 6);
  const syStart = baseStartYear - yearsSinceGrade6;
  const syEnd = syStart + 1;
  return {
    syStart: String(syStart),
    syEnd: String(syEnd),
  };
}
